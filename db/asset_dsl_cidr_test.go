package db

import (
	"strings"
	"testing"
)

// cidr is the most frequent asset query in pentesting ("which hosts are in this network?"). Before the DSL had it,
// agents could only try `ip >= 10.0.0.0`, but ip is a string field with no comparison operators —
// measured: 24 "string field ip does not support operator >=" + 11 syntax errors — all of them
// forced out by this single missing capability.
func TestValidateDSLAcceptsCidr(t *testing.T) {
	for _, ok := range []string{
		"cidr=10.10.0.0/16",
		"cidr==192.168.1.0/24",
		"cidr=10.0.0.0/8 AND port==443",
		"cidr=10.0.0.0/8 OR cidr=172.16.0.0/12",
	} {
		if err := ValidateDSL(ok); err != nil {
			t.Errorf("ValidateDSL(%q) should pass: %v", ok, err)
		}
	}
}

// cidr's value must be a network, not a bare IP or garbage.
func TestValidateDSLRejectsBadCidr(t *testing.T) {
	for _, bad := range []string{
		"cidr=10.10.70.17",     // bare IP, not a network
		"cidr=not-a-network",   // garbage
		"cidr=10.10.0.0/16/24", // extra segment
	} {
		if err := ValidateDSL(bad); err == nil {
			t.Errorf("ValidateDSL(%q) should error", bad)
		}
	}
}

// SQL generated by cidr must use the inet containment operator (>>=) and be safe for non-IP ip values
// (try_inet returns NULL instead of throwing 22P02).
func TestBuildDSLWhereCidrUsesInetContainment(t *testing.T) {
	node, err := ParseDSL("cidr=10.10.0.0/16")
	if err != nil {
		t.Fatal(err)
	}
	where, args, err := buildDSLWhere(node)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(where, "try_inet(ip)") || !strings.Contains(where, ">>=") {
		t.Errorf("where=%q should use try_inet(ip) >>= network", where)
	}
	if len(args) != 1 || args[0] != "10.10.0.0/16" {
		t.Errorf("args=%v should contain exactly one network argument", args)
	}
}

// Semantics of cidr !=: everything outside the network counts (including NULL, since ip may be a hostname).
func TestBuildDSLWhereCidrNotEqual(t *testing.T) {
	node, err := ParseDSL("cidr!=10.10.0.0/16")
	if err != nil {
		t.Fatal(err)
	}
	where, _, err := buildDSLWhere(node)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(where, "NOT") {
		t.Errorf("where=%q should contain NOT", where)
	}
}
