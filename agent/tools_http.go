package agent

// Native HTTP executor (v0.7.0): http_request / session_login.
//
// ## Why it exists
//
// Field diagnostics (v0.6.32) showed: every worker probe was 'domain tool builds command → model calls
// Bash to run it' — two round-trips; curl 2750 times, python3 glue 2105 times, and full responses dumped into chat.
// More importantly there was no session concept: auth_request could only build curl — login state couldn't be
// reused by later requests; the most basic 'login → privesc → read-back' chain needed the model to carry cookies itself, and one slip meant death.
//
// This tool issues requests directly in Go (through the same recording proxy + the same task-level cookie jar),
// returning structured results in one call: status/headers/body snippet/on-disk pointer.
//
// ## Control boundary
//
//   - Identical egress as Bash: the scan proxy injected by Worker.SetProxy (recording MITM or global proxy),
//     plus trusting its CA — traffic still lands in the traffic viewer; no bypassing the trail.
//   - It's a 'can act on targets' tool, registered in localExecToolNames: agents with local_exec=false
//     can't reach it (same gate as Bash/http_probe).
//   - The cookie jar lives at tasks/<id>/shared/sessions/<name>.jar (curl-compatible Netscape
//     format), shared with auth_request/session_request's `-b/-c` — native requests
//     and curl commands can alternate on the same login state.

