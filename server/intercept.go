// --- helpers ---

type interceptRuleReq struct {
	Name           string `json:"name"`
	Enabled        bool   `json:"enabled"`
	Priority       int    `json:"priority"`
	MatchTarget    string `json:"match_target"`
	MatchType      string `json:"match_type"`
	Pattern        string `json:"pattern"`
	Action         string `json:"action"`
	Message        string `json:"message"`
	TimeoutEnabled bool   `json:"timeout_enabled"`
	TimeoutSeconds int    `json:"timeout_seconds"`
	TimeoutAction  string `json:"timeout_action"`
}

func validateInterceptRuleReq(req interceptRuleReq) error {
	if req.Name == "" {
		return fmt.Errorf("name must not be empty")
	}
	switch req.MatchTarget {
	case "tool_name", "tool_input":
	default:
		return fmt.Errorf("match_target must be tool_name or tool_input")
	}
	switch req.MatchType {
	case "string", "regex":
	default:
		return fmt.Errorf("match_type must be string or regex")
	}
	if req.Pattern == "" {
		return fmt.Errorf("pattern must not be empty")
	}
	switch req.Action {
	case "allow", "deny", "ask", "judge":
	default:
		return fmt.Errorf("action must be allow, deny, ask or judge")
	}
	if req.MatchType == "regex" {
		if _, err := regexp.Compile(req.Pattern); err != nil {
			return fmt.Errorf("pattern is not a valid regex: %w", err)
		}
	}
	// timeout_action must be inside the allowed set.
	//
	// This field **actually took effect** on 2026-10-22 (a rule's own timeout
	// declaration beats the global judge config), so it stopped being just a stored
	// string: arbitrary values would make 'allow or deny after timeout' undefined —
	// `dec.TimeoutAction == "allow"` treats anything non-"allow" as deny, while the UI
	// displays whatever garbage was written.
	switch req.TimeoutAction {
	case "allow", "deny":
	default:
		return fmt.Errorf("timeout_action must be allow or deny")
	}
	if req.TimeoutEnabled && req.TimeoutSeconds <= 0 {
		return fmt.Errorf("timeout_seconds must be positive when timeout is enabled")
	}
	return nil
}

