// judgeWorkerLane is the usage-ledger "worker" label for intercept fallback-judge
// calls, so judge spend can be queried apart from the worker/planner/main lanes.
const judgeWorkerLane = "judge"

// chatGuard returns a guard wired with the manager's interceptor, used for chat
// conversations. Called once per applyLLM so a new LLM config always gets a fresh guard.
func (s *Server) chatGuard() *guard.Guard {
	return guard.NewWithInterceptor(s.m.interceptor)
}

// wireInterceptReviewer installs the LLM fallback judge into the interceptor. The
// judge runs only on tool calls that matched no rule (see intercept.Judge). It
// resolves the configured judge profile (0 → active/default), builds a provider,
// runs a one-shot JSON classification with an explanation for every verdict.
func (s *Server) wireInterceptReviewer() {
	s.m.interceptor.SetReviewer(func(ctx context.Context, profileID int64, prompt string, input intercept.ReviewInput) (intercept.Decision, error) {
		if profileID == 0 {
			if p, err := s.m.pg.ActiveProfile(); err == nil && p != nil {
				profileID = p.ID
			}
		}
		if profileID == 0 {
			return intercept.Decision{}, fmt.Errorf("no usable judge model configured")
		}
		prov, _, ok := s.providerForProfile(profileID)
		if !ok {
			return intercept.Decision{ProfileID: profileID}, fmt.Errorf("judge model profile %d unavailable", profileID)
		}
		// Tag this call's usage as the "judge" lane so the config page can report
		// how much the fallback approval has spent, separate from model profiles.
		ctx = llmrec.WithWorker(ctx, judgeWorkerLane)
		text, err := reviewCompletion(ctx, prov, prompt, input)
		if err != nil {
			return intercept.Decision{ProfileID: profileID}, err
		}
		v := intercept.ParseVerdict(text)
		if v.Action == "" {
			// splice a chunk of the model's raw reply into the error — on parse failure
			// a bare 'invalid format' is undebuggable (missing a section? wrong
			// delimiter? max_tokens truncation?).
			//
			// Two 'parse failures' need distinguishing:
			//   - empty reply: thinking burned the whole budget before a single body
			//     token (common on long commands);
			//   - reply truncated to `{"decision":"al`: JSON unfinished — also a budget
			//     shortage.
			// Same cure both ways: generous budget + escalating-budget retries.
			// streamCollectTextBudget above already handles 'empty reply'; this adds
			// the 'content exists but won't parse' retry.
			if retryText, retryErr := reviewCompletionEscalate(ctx, prov, prompt, input, text); retryErr == nil {
				text = retryText
				v = intercept.ParseVerdict(text)
			}
		}
		if v.Action == "" {
			return intercept.Decision{ProfileID: profileID},
				fmt.Errorf("model verdict format invalid (need decision + three comment sections): raw reply %.400q", text)
		}
		return intercept.Decision{Action: v.Action, Message: v.Reason, ProfileID: profileID}, nil
	})
}

// reviewCompletionEscalate retries once with a higher budget when 'there's content but
// the verdict won't parse'. Typical case: JSON cut mid-stream by max_tokens
// (`{"decision":"al`).
func reviewCompletionEscalate(ctx context.Context, prov llm.Provider, prompt string, input intercept.ReviewInput, first string) (string, error) {
	user, err := json.Marshal(input)
	if err != nil {
		return "", err
	}
	for _, b := range judgeRetryBudgets {
		if ctx.Err() != nil {
			return "", ctx.Err()
		}
		text, err := oneCompletion(ctx, prov, prompt, string(user), b)
		if err != nil {
			return "", err
		}
		if intercept.ParseVerdict(text).Action != "" {
			return text, nil
		}
	}
	return first, nil
}

func reviewCompletion(ctx context.Context, prov llm.Provider, prompt string, input intercept.ReviewInput) (string, error) {
	user, err := json.Marshal(input)
	if err != nil {
		return "", err
	}
	return streamCollectText(ctx, prov, prompt, string(user))
}

// streamCollectText runs a single non-streaming-style completion (low
// temperature, bounded output) and returns the concatenated text.
//
// thinking handling: this used to hardcode Thinking:"disabled" — models like
// MiniMax-M3.1 that **mandate adaptive thinking** get flatly refused upstream (400
// "requires adaptive thinking; thinking.type=disabled is not allowed"), making verdicts
// fail 100% of the time; with the failure policy defaulting to allow, the gate was
// effectively dead.
//
// Now the thinking field is omitted by default (empty = let model/gateway follow their
// own defaults), driven by the profile's thinking_type; only sent when explicitly
// configured.
//
// max_tokens must be generous: thinking-enabled models count thought tokens against
// the output quota — **thinking and body share one budget**. Long commands
// (hundreds-to-thousands of chars of shell) on a 2048 budget left the body empty
// (verdict records showed 'raw reply ""'); short commands fit in 2048. So we give
// 32768 outright and **retry with escalating budgets** when the body comes back empty —
// better to spend extra quota than let this gate silently die of starvation.
func streamCollectText(ctx context.Context, prov llm.Provider, system, user string) (string, error) {
	return streamCollectTextBudget(ctx, prov, system, user, judgeMaxTokens)
}

// judgeMaxTokens is the verdict output budget (thinking + body share it).
//
// Why 32768: measured on the same model, long commands at 2048 left 'thinking burned
// out, body empty' while short ones fit. With the full budget even long commands emit
// the three-section JSON fine.
const judgeMaxTokens = 32768

// judgeRetryBudgets is the retry budget ladder for empty bodies.
//
// Why a ladder: empty-body causes scale with command length (longer input → longer
// thinking), so a fixed budget is either always insufficient or wasteful on short
// commands. Escalation guarantees long commands produce a verdict while short ones
// aren't inflated pointlessly.
//
// The ladder must be **strictly above** the first budget: first is 32768, the ladder
// starts at 65536 — otherwise the first retry would ask the same question with the same
// budget, a wasted round trip.
var judgeRetryBudgets = []int{65536, 131072}

// streamCollectTextBudget fetches one reply at the given budget; an empty body retries
// up the ladder.
func streamCollectTextBudget(ctx context.Context, prov llm.Provider, system, user string, budget int) (string, error) {
	var last string
	for i, b := range append([]int{budget}, judgeRetryBudgets...) {
		if i > 0 {
			// check ctx budget before retrying: verdicts have their own timeout (90s
			// default), and long commands are already slow — don't burn the remainder
			// on retries doomed to time out.
			if ctx.Err() != nil {
				return last, ctx.Err()
			}
		}
		text, err := oneCompletion(ctx, prov, system, user, b)
		if err != nil {
			return "", err
		}
		if strings.TrimSpace(text) != "" {
			return text, nil
		}
		last = text
	}
	return last, nil
}

// oneCompletion issues one budgeted completion request, returning the concatenated
// text.
func oneCompletion(ctx context.Context, prov llm.Provider, system, user string, maxTokens int) (string, error) {
	temp := 0.0
	req := llm.CompletionRequest{
		System:      []string{system},
		Messages:    []llm.Message{llm.UserText(user)},
		MaxTokens:   maxTokens,
		Temperature: &temp,
	}
	var sb strings.Builder
	for ev, err := range prov.Stream(ctx, req) {
		if err != nil {
			return "", err
		}
		if ev.Type == llm.SETextDelta {
			sb.WriteString(ev.Text)
		}
	}
	return sb.String(), nil
}

// --- intercept rule CRUD ---

func (s *Server) interceptListRules(w http.ResponseWriter, r *http.Request) {
	pg := s.pg(w)
	if pg == nil {
		return
	}
	rules, err := pg.ListInterceptRules()
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	if rules == nil {
		rules = []db.InterceptRule{}
	}
	writeJSON(w, 200, map[string]any{"rules": rules})
}

func (s *Server) interceptCreateRule(w http.ResponseWriter, r *http.Request) {
	pg := s.pg(w)
	if pg == nil {
		return
	}
	var req interceptRuleReq
	if err := decode(r, &req); err != nil {
		writeErr(w, 400, err.Error())
		return
	}
	if err := validateInterceptRuleReq(req); err != nil {
		writeErr(w, 400, err.Error())
		return
	}
	rule, err := pg.CreateInterceptRule(req.Name, req.MatchTarget, req.MatchType, req.Pattern, req.Action, req.Message, req.Priority, req.Enabled, req.TimeoutEnabled, req.TimeoutSeconds, req.TimeoutAction)
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	s.m.interceptor.Invalidate()
	writeJSON(w, 200, rule)
}

